#!/usr/bin/env python
"""Generate a module-definition file for a DLL that is too big for "export everything".

usage: python gen_def.py --out X.def --name Main --provider @objs.rsp --consumer @objs.rsp [--consumer ...]

Exports = symbols defined (external) in the provider's object files that are referenced but not defined
by the consumers' object files. This replaces the tool-generated ReleaseDll.def of the original build
(VC7/STLport manglings, unusable today) and stays under the 65535-export limit of the PE format, which
CMake's WINDOWS_EXPORT_ALL_SYMBOLS exceeds for Main.

Needs dumpbin.exe on PATH (any VS developer prompt).
"""
import argparse, concurrent.futures, re, subprocess, sys

ap = argparse.ArgumentParser()
ap.add_argument('--out', required=True)
ap.add_argument('--name', required=True)
ap.add_argument('--provider', action='append', default=[])
ap.add_argument('--consumer', action='append', default=[])
a = ap.parse_args()


def expand(items):
    out = []
    for it in items:
        if it.startswith('@'):
            out += open(it[1:]).read().replace(';', '\n').split('\n')
        else:
            out.append(it)
    return [x.strip().strip('"') for x in out if x.strip()]


SYM = re.compile(r'^[0-9A-F]+ [0-9A-F]+ (\S+)\s+notype( \(\))?\s+External\s+\| (\S+)')


def symbols(obj):
    txt = subprocess.run(['dumpbin', '/nologo', '/symbols', obj], capture_output=True, text=True, errors='replace').stdout
    defined, undefined = {}, set()
    for line in txt.splitlines():
        m = SYM.match(line)
        if not m:
            continue
        sect, is_func, name = m.group(1), bool(m.group(2)), m.group(3)
        if sect == 'UNDEF':
            undefined.add(name)
        elif sect.startswith('SECT'):
            defined[name] = is_func
    return defined, undefined


def scan(objs):
    defined, undefined = {}, set()
    with concurrent.futures.ThreadPoolExecutor(8) as ex:
        for d, u in ex.map(symbols, objs):
            defined.update(d)
            undefined |= u
    return defined, undefined


prov_def, _ = scan(expand(a.provider))
cons_def, cons_undef = scan(expand(a.consumer))

exports = {}
for name in cons_undef:
    via_imp = name.startswith('__imp_')
    real = name[6:] if via_imp else name
    if real in cons_def or real not in prov_def:
        continue
    is_func = prov_def[real]
    exports[real] = (not is_func) and via_imp


def export_name(sym):
    # C++ decorated and __fastcall/__stdcall names go in verbatim; __cdecl C names lose the leading '_'.
    if sym.startswith('?') or sym.startswith('@'):
        return sym
    return sym[1:] if sym.startswith('_') else sym


with open(a.out, 'w', newline='\n') as f:
    f.write('; generated by vs2022/tools/gen_def.py - do not edit\n')
    f.write('LIBRARY %s\nEXPORTS\n' % a.name)
    for sym in sorted(exports):
        f.write('\t%s%s\n' % (export_name(sym), ' DATA' if exports[sym] else ''))
print('gen_def: %s exports %d symbols (%d data)' % (a.name, len(exports), sum(exports.values())))
